from uuid import UUID

from pydantic import BaseModel, Field


class PlayerRegisterRequest(BaseModel):
    """Регистрация устройства.

    ``device_id`` необязателен, но без него прогресс не переживёт переустановку
    приложения: токен теряется вместе с данными приложения, а в базе лежит
    только его хеш. С ``device_id`` та же запись находится и получает свежий
    токен.

    На Android источник — ``Settings.Secure.ANDROID_ID``: переживает
    переустановку, скоупится по ключу подписи приложения, разрешений не требует
    и рекламным идентификатором не является.
    """

    device_id: str | None = Field(default=None, min_length=1, max_length=128)


class PlayerUpdateRequest(BaseModel):
    """Изменение игрока.

    ВНИМАНИЕ: xp_total — единственное изменяемое поле, и это единственное место
    во всём API, где клиент пишет значение, которое иначе выводит сервер.
    Токен менять нельзя (в базе только хеш), device_id — идентичность,
    created_at — метаданные строки, ников в проекте нет.

    Пока нет лидерборда, накрутивший опыт обманул только себя — ровно как
    записано в CLAUDE.md про токен. Появится лидерборд — эту ручку надо
    закрывать первой.
    """

    xp_total: int = Field(ge=0)


class PlayerRegisteredResponse(BaseModel):
    """Ответ на регистрацию устройства.

    Единственное место во всём API, где виден сам токен: в базе лежит только
    его sha256, и повторно показать его невозможно.
    """

    player_id: UUID
    token: str
    xp_total: int
    level: int
    # True, если устройство уже было зарегистрировано и запись нашлась
    # по device_id: игрок вернулся с прежним прогрессом, а токен обновлён.
    restored: bool


class PlayerStateResponse(BaseModel):
    """Текущее состояние игрока.

    Нужен клиенту, чтобы сверить локальное состояние с серверным после
    возвращения в сеть: игра офлайновая, и расхождение — норма.
    """

    player_id: UUID
    xp_total: int
    level: int
    xp_into_level: int
    xp_to_next: int


class PlayerDeletedResponse(BaseModel):
    """Подтверждение удаления игрока.

    Число удалённых партий возвращается явно: они уходят каскадом по внешнему
    ключу, и молчать о том, сколько данных исчезло, нечестно.
    """

    player_id: UUID
    games_deleted: int
